"""End-to-end RAG answering chain connecting retrieval, prompt construction, Ollama, and validation."""

from dataclasses import dataclass, field
from typing import Any, Dict, Generator, List, Optional
import uuid

from app.core.config import settings
from app.core.logging import logger
from app.retrieval.base import RetrievedChunk
from app.retrieval.retrieval_pipeline import RetrievalPipeline
from app.generation.ollama_client import OllamaClient
from app.generation.prompt_builder import PromptBuilder, RAG_SYSTEM_PROMPT
from app.generation.citation_manager import CitationManager, CitationItem
from app.generation.answer_validator import AnswerValidator, ABSTENTION_MESSAGE
from app.memory.conversation_manager import ConversationManager


@dataclass
class RAGResponse:
    """The complete response generated by the RAG answering engine."""
    question: str
    answer: str
    citations: List[Dict[str, Any]]
    source_cards: List[Dict[str, Any]]
    retrieved_chunks: List[RetrievedChunk]
    is_grounded: bool
    is_abstained: bool
    validation_warnings: List[str] = field(default_factory=list)
    session_id: Optional[str] = None


class RAGChain:
    """Executes the complete grounded document Q&A workflow."""

    def __init__(
        self,
        retrieval_pipeline: RetrievalPipeline,
        ollama_client: Optional[OllamaClient] = None,
        conversation_manager: Optional[ConversationManager] = None,
    ):
        self.retrieval_pipeline = retrieval_pipeline
        self.ollama_client = ollama_client or OllamaClient()
        self.conversation_manager = conversation_manager or ConversationManager()

    def query(
        self,
        question: str,
        session_id: Optional[str] = None,
        filter_criteria: Optional[Dict[str, Any]] = None,
        top_k: Optional[int] = None,
    ) -> RAGResponse:
        """Executes full RAG retrieval, Ollama generation, citation validation, and memory persistence."""
        sid = session_id or str(uuid.uuid4())

        # 1. Load conversation history
        history = self.conversation_manager.get_history(sid)

        # 2. Retrieve relevant chunks
        chunks = self.retrieval_pipeline.retrieve(
            query=question,
            top_k=top_k or settings.TOP_K,
            filter_criteria=filter_criteria,
            conversation_history=history,
        )

        source_cards = CitationManager.build_source_cards(chunks)

        # 3. Check retrieval sufficiency
        if not AnswerValidator.check_retrieval_sufficiency(chunks):
            logger.info("Retrieval insufficient for question '%s'. Returning abstention.", question)
            self.conversation_manager.add_user_message(sid, question)
            self.conversation_manager.add_assistant_message(sid, ABSTENTION_MESSAGE, sources=[])
            return RAGResponse(
                question=question,
                answer=ABSTENTION_MESSAGE,
                citations=[],
                source_cards=source_cards,
                retrieved_chunks=chunks,
                is_grounded=True,
                is_abstained=True,
                validation_warnings=["Insufficient context retrieved to answer accurately."],
                session_id=sid,
            )

        # 4. Construct grounded prompt
        user_prompt = PromptBuilder.build_user_prompt(
            question=question,
            chunks=chunks,
            conversation_history=history,
        )

        # 5. Generate answer from Ollama
        raw_answer = self.ollama_client.generate(
            prompt=user_prompt,
            system_prompt=RAG_SYSTEM_PROMPT,
        )

        # 6. Validate citations and strip fabricated references
        citations, validated_text = CitationManager.validate_citations(raw_answer, chunks)

        # 7. Validate grounding and numerical consistency
        validation_result = AnswerValidator.validate_answer(question, validated_text, chunks)

        final_answer = validation_result["validated_answer"]
        is_abstained = validation_result["should_abstain"]
        is_grounded = validation_result["is_grounded"]
        warnings = validation_result["warnings"]

        # 8. Record turns in conversation memory
        citation_dicts = [c.to_dict() for c in citations if c.is_valid]
        self.conversation_manager.add_user_message(sid, question)
        self.conversation_manager.add_assistant_message(sid, final_answer, sources=citation_dicts)

        return RAGResponse(
            question=question,
            answer=final_answer,
            citations=citation_dicts,
            source_cards=source_cards,
            retrieved_chunks=chunks,
            is_grounded=is_grounded,
            is_abstained=is_abstained,
            validation_warnings=warnings,
            session_id=sid,
        )

    def stream_query(
        self,
        question: str,
        session_id: Optional[str] = None,
        filter_criteria: Optional[Dict[str, Any]] = None,
        top_k: Optional[int] = None,
    ) -> Generator[Dict[str, Any], None, None]:
        """Streams answer generation tokens while reporting sources and performing validation."""
        sid = session_id or str(uuid.uuid4())
        history = self.conversation_manager.get_history(sid)

        # 1. Retrieve candidates
        chunks = self.retrieval_pipeline.retrieve(
            query=question,
            top_k=top_k or settings.TOP_K,
            filter_criteria=filter_criteria,
            conversation_history=history,
        )

        source_cards = CitationManager.build_source_cards(chunks)
        # Yield retrieved source cards immediately to the UI
        yield {"type": "sources", "data": source_cards, "session_id": sid}

        # 2. Check retrieval sufficiency
        if not AnswerValidator.check_retrieval_sufficiency(chunks):
            yield {"type": "token", "content": ABSTENTION_MESSAGE}
            self.conversation_manager.add_user_message(sid, question)
            self.conversation_manager.add_assistant_message(sid, ABSTENTION_MESSAGE, sources=[])
            yield {
                "type": "done",
                "citations": [],
                "is_grounded": True,
                "is_abstained": True,
                "warnings": ["Insufficient context retrieved to answer."],
            }
            return

        # 3. Build grounded prompt
        user_prompt = PromptBuilder.build_user_prompt(
            question=question,
            chunks=chunks,
            conversation_history=history,
        )

        # 4. Stream tokens from Ollama
        accumulated_tokens = []
        for token in self.ollama_client.stream_generate(prompt=user_prompt, system_prompt=RAG_SYSTEM_PROMPT):
            if not token:
                # Periodic keep-alive heartbeat while Ollama evaluates prompt
                yield {"type": "ping"}
                continue
            accumulated_tokens.append(token)
            yield {"type": "token", "content": token}

        full_raw_answer = "".join(accumulated_tokens)

        # 5. Post-generation validation
        citations, validated_text = CitationManager.validate_citations(full_raw_answer, chunks)
        validation_result = AnswerValidator.validate_answer(question, validated_text, chunks)

        final_answer = validation_result["validated_answer"]
        citation_dicts = [c.to_dict() for c in citations if c.is_valid]

        self.conversation_manager.add_user_message(sid, question)
        self.conversation_manager.add_assistant_message(sid, final_answer, sources=citation_dicts)

        yield {
            "type": "done",
            "answer": final_answer,
            "citations": citation_dicts,
            "is_grounded": validation_result["is_grounded"],
            "is_abstained": validation_result["should_abstain"],
            "warnings": validation_result["warnings"],
        }
